PURPOSE = {
    "overdraft": "CASH_GAP",
    "equipment": "EQUIPMENT",
    "transport": "TRANSPORT",
    "property": "COMMERCIAL_PROPERTY",
    "investment": "DEVELOPMENT",
    "contract": "CONTRACT_EXECUTION",
    "refinance": "REFINANCING",
    "no_relevant": "DEVELOPMENT",
}
REL = {
    "ordinary": ["P01", "P02"],
    "seasonal": ["P01", "P02", "P06"],
    "marketplace": ["P01", "P02", "P14"],
    "revolving": ["P03"],
    "nonrevolving": ["P04"],
    "overdraft": ["P05"],
    "equipment": ["P07"],
    "transport": ["P08"],
    "property": ["P09"],
    "investment": ["P10"],
    "contract": ["P11"],
    "refinance": ["P12"],
    "ip": ["P01", "P02", "P13"],
    "no_relevant": [],
    "restricted_catalog": [],
}


def build():
    source = ROOT / "evaluation/backend-products.json"
    products = json.loads(source.read_text(encoding="utf-8"))["products"]
    datasets = {"calibration": [], "holdout": []}
    for intent, families in CASES.items():
        for index, (sector, description) in enumerate(families):
            split = "calibration" if index < 4 else "holdout"
            family = f"new-{intent}-{index + 1:02}"
            for variant in range(3):
                purpose = PURPOSE.get(intent, "WORKING_CAPITAL")
                usage = (
                    "ACCOUNT_RESERVE"
                    if intent == "overdraft"
                    else "IN_PARTS"
                    if intent in ("revolving", "nonrevolving")
                    else "ONE_TIME"
                )
                if intent == "restricted_catalog":
                    usage = "IN_PARTS" if index in (0, 2, 4) else "ONE_TIME"
                secured = intent in ("equipment", "transport", "property", "investment", "refinance")
                collateral = (
                    ["YES", "DISCUSS", "UNKNOWN"][variant]
                    if secured
                    else ["NO", "UNKNOWN", "DISCUSS"][variant]
                )
                guarantor = ["YES", "DISCUSS", "UNKNOWN"][(index + variant) % 3]
                # Cover explicit NO separately, without contradicting a required guarantor.
                if intent == "ip" and variant == 2:
                    guarantor = "NO"
                text = description
                if variant == 1:
                    text = (
                        "Контекст обращения: "
                        + text
                        + " Деньги используем для указанной задачи, без изменения назначения."
                    )
                if variant == 2:
                    text += " В компании несколько сотрудников, ведём планирование платежей и хотим сравнить доступные предложения."
                if intent == "ordinary" and variant == 2:
                    text = None
                profile = {
                    "business": {"sector": sector if variant != 1 else None},
                    "request": {
                        "purpose": purpose,
                        "usageMode": usage if variant != 2 else "UNKNOWN",
                        "description": text,
                    },
                    "security": {"collateralReady": collateral, "guarantorReady": guarantor},
                }
                candidates = [
                    p["code"]
                    for p in products
                    if purpose in p["purposes"]
                    and (profile["request"]["usageMode"] == "UNKNOWN" or usage in p["usageModes"])
                    and (p["code"] != "P13" or intent == "ip")
                    and (p["code"] != "P15" or sector == "MANUFACTURING")
                ]
                relevant = list(REL[intent])
                if intent == "equipment" and sector == "MANUFACTURING":
                    relevant.append("P15")
                if intent == "investment" and sector == "MANUFACTURING":
                    relevant = ["P01", "P10", "P15"]
                if intent == "restricted_catalog":
                    candidates = ["P04"] if index in (0, 4) else ["P03"] if index == 2 else ["P06", "P14"]
                relevant = sorted(set(relevant) & set(candidates))
                datasets[split].append(
                    {
                        "id": family + f"-v{variant + 1}",
                        "familyId": family,
                        "intent": intent,
                        "profile": profile,
                        "candidateProductCodes": candidates,
                        "relevantProductCodes": relevant,
                        "labelStatus": "SYNTHETIC_PROPOSED",
                        "labelRationale": "Semantic suitability for the explicitly stated task; specialized seasonal/marketplace products require positive evidence, unknown is not positive evidence. Labels authored before inference, not approval decisions.",
                    }
                )
    manifest = {
        "datasetVersion": "synthetic-calibration-1",
        "labelStatus": "SYNTHETIC_PROPOSED",
        "productsSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "splitRule": "Business families 1-4 per intent in calibration, families 5-6 in holdout. All variants of a family stay together. Never includes previous 40 ML or 8 backend scenarios.",
        "objective": "Maximize micro F1 of actual recommended pairs after topK=3; ties prefer higher precision then smaller maximum distance.",
        "notice": "Human review required. Synthetic scenario families are not real users. High diversity does not establish representativeness.",
    }
    for split, rows in datasets.items():
        path = ROOT / f"evaluation/{split}.json"
        path.write_text(
            json.dumps({**manifest, "split": split, "scenarios": rows}, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    assert not (
        {s["familyId"] for s in datasets["calibration"]} & {s["familyId"] for s in datasets["holdout"]}
    )
    print(json.dumps({k: len(v) for k, v in datasets.items()}))


if __name__ == "__main__":
    build()
